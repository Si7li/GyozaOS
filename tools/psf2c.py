#!/usr/bin/env python3
"""Convert a PSF2 console font into a C header the kernel can link in.

    ./tools/psf2c.py                          # defaults, writes drivers/font.h
    ./tools/psf2c.py FONT.psfu OUT.h          # explicit paths
    ./tools/psf2c.py --preview A              # render one glyph as ASCII art

Only PSF2 fonts that are 8 pixels wide are supported, because the kernel's
blitter assumes exactly one byte per glyph row.
"""

import argparse
import gzip
import struct
import sys
from pathlib import Path

PSF2_MAGIC = b"\x72\xb5\x4a\x86"
GZIP_MAGIC = b"\x1f\x8b"

# After the 4 magic bytes: version, headersize, flags, length, charsize,
# height, width -- seven little-endian uint32s, so 32 bytes of header total.
PSF2_HEADER = "<7I"

DEFAULT_INPUT = "/usr/share/kbd/consolefonts/default8x16.psfu.gz"
DEFAULT_OUTPUT = "kernel/src/drivers/font.h"


class Font:
    def __init__(self, glyphs, width, height, source):
        self.glyphs = glyphs      # list of `height` bytes per glyph
        self.width = width
        self.height = height
        self.source = source

    def __len__(self):
        return len(self.glyphs)


def load(path):
    """Read a PSF2 file (transparently gunzipped) and pull out the bitmaps."""
    raw = Path(path).read_bytes()
    if raw[:2] == GZIP_MAGIC:
        raw = gzip.decompress(raw)

    if raw[:4] != PSF2_MAGIC:
        sys.exit(f"{path}: not a PSF2 font (magic {raw[:4].hex()}). "
                 "PSF1 fonts are not supported; pick a .psfu file.")

    version, headersize, _flags, count, charsize, height, width = struct.unpack_from(
        PSF2_HEADER, raw, 4
    )

    if version != 0:
        sys.exit(f"{path}: unsupported PSF2 version {version}")
    if width != 8:
        sys.exit(f"{path}: font is {width} pixels wide; only 8 is supported")

    bytes_per_row = (width + 7) // 8
    if charsize != height * bytes_per_row:
        sys.exit(f"{path}: charsize {charsize} disagrees with {width}x{height}")

    needed = headersize + count * charsize
    if len(raw) < needed:
        sys.exit(f"{path}: truncated, need {needed} bytes but file has {len(raw)}")

    glyphs = [
        list(raw[headersize + i * charsize : headersize + (i + 1) * charsize])
        for i in range(count)
    ]
    return Font(glyphs, width, height, Path(path).name)


def preview(font, char):
    """Print one glyph as ASCII art so you can eyeball that parsing worked."""
    index = ord(char)
    if index >= len(font):
        sys.exit(f"glyph {index} is out of range (font has {len(font)})")

    print(f"glyph 0x{index:02X} {char!r}  ({font.width}x{font.height})")
    for row in font.glyphs[index]:
        bits = "".join("#" if row & (0x80 >> c) else "." for c in range(font.width))
        print(f"  {bits}  0x{row:02X}")


def emit(font, out_path, in_path):
    lines = [
        f"// Generated by tools/psf2c.py from {font.source} -- do not edit by hand.",
        f"// Regenerate with: ./tools/psf2c.py {in_path} {out_path}",
        "",
        "#ifndef FONT_H",
        "#define FONT_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_WIDTH  {font.width}",
        f"#define FONT_HEIGHT {font.height}",
        f"#define FONT_GLYPHS {len(font)}",
        "",
        "// One byte per row, FONT_HEIGHT rows per glyph.",
        "// Bit 7 (0x80) is the LEFTMOST pixel -- get this backwards and text mirrors.",
        "static const uint8_t font8x16[FONT_GLYPHS][FONT_HEIGHT] = {",
    ]

    for index, glyph in enumerate(font.glyphs):
        char = chr(index)
        label = repr(char) if char.isprintable() and index < 127 else ""
        lines.append(f"    /* 0x{index:02X} {label} */")
        for start in range(0, len(glyph), 8):
            chunk = ", ".join(f"0x{b:02X}" for b in glyph[start : start + 8])
            opener = "    { " if start == 0 else "      "
            closer = " }," if start + 8 >= len(glyph) else ","
            lines.append(f"{opener}{chunk}{closer}")

    lines += ["};", "", "#endif", ""]

    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(lines))
    print(f"wrote {out_path}: {len(font)} glyphs, {font.width}x{font.height}")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", nargs="?", default=DEFAULT_INPUT)
    ap.add_argument("output", nargs="?", default=DEFAULT_OUTPUT)
    ap.add_argument("--preview", metavar="CHAR",
                    help="render this character as ASCII art instead of writing a header")
    args = ap.parse_args()

    font = load(args.input)

    if args.preview:
        preview(font, args.preview[0])
    else:
        emit(font, args.output, args.input)


if __name__ == "__main__":
    main()
